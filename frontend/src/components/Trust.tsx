import { useEffect, useState } from 'react';
import { BASE } from '../store/useStore';

interface Test {
  id: number;
  name: string;
  reference: string;
  threshold: string;
  result: string;
  pass: boolean | null;
  detail?: string;
}
interface Cal {
  bin: string;
  n: number;
  ref: number | null;
  ours: number | null;
}
interface Validation {
  generated: string;
  tests: Test[];
  convergence?: { site: string; rows: { label: string; sunPct: number; maxHorizon: number }[] }[];
  gaps: string[];
  external?: {
    pgda?: {
      sun: Stat;
      earth: Stat;
      byDomain: { domain: string; n: number; sunBias: number; sunR: number; earthBias: number; earthR: number }[];
      calibrationSun: Cal[];
      calibrationEarth: Cal[];
    };
    wacPct?: { calibration: Cal[] };
    frames?: {
      rows: {
        frame: string;
        utc: string;
        otsuDN: number;
        points: number;
        litImagePct: number;
        litPredictedPct: number;
        mcc: number;
        mccMirrored: number;
        mccShifted7d: number;
      }[];
      pooledMcc: Record<string, number>;
      orientationScan: Record<string, number>;
    };
  };
}
interface Stat {
  n: number;
  bias: number;
  rmse: number;
  r: number;
  rLit: number;
}
const f = (x: number | null | undefined, d = 1) => (x == null ? '–' : x.toFixed(d));
function CalTable({ title, rows }: { title: string; rows: Cal[] }) {
  return (
    <div>
      <b>{title}</b>
      <table>
        <thead>
          <tr>
            <th>Reference</th>
            <th>n</th>
            <th>Reference mean</th>
            <th>Ours</th>
            <th>Δ</th>
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r.bin}>
              <td>{r.bin}</td>
              <td>{r.n}</td>
              <td>{f(r.ref)}%</td>
              <td>{f(r.ours)}%</td>
              <td>
                {r.ref != null && r.ours != null ? (r.ours - r.ref >= 0 ? '+' : '') + (r.ours - r.ref).toFixed(1) : '–'}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

export function Trust() {
  const [v, setV] = useState<Validation | null>(null),
    [err, setErr] = useState('');
  useEffect(() => {
    fetch(BASE + 'validation.json')
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(String(r.status)))))
      .then(setV)
      .catch((e) => setErr(String(e.message)));
  }, []);
  return (
    <div className="grid">
      <div className="card">
        <h3>
          Validation{' '}
          <span className="faint" style={{ textTransform: 'none', letterSpacing: 0 }}>
            regenerated by the pipeline, not typed
          </span>
        </h3>
        {!v ? (
          <div className="muted">
            {err ? `validation.json is not available (${err}). Run npm run validate.` : 'Loading…'}
          </div>
        ) : (
          <>
            <table>
              <thead>
                <tr>
                  <th>#</th>
                  <th>Test</th>
                  <th>Reference</th>
                  <th>Threshold</th>
                  <th>Result</th>
                </tr>
              </thead>
              <tbody>
                {v.tests.map((t) => (
                  <tr key={t.id}>
                    <td>{t.id}</td>
                    <td>
                      <b>{t.name}</b>
                      {t.detail && <div className="faint small">{t.detail}</div>}
                    </td>
                    <td className="small">{t.reference}</td>
                    <td className="small">{t.threshold}</td>
                    <td>
                      <span className={'badge ' + (t.pass === true ? 'ok' : t.pass === false ? 'bad' : 'warn')}>
                        {t.pass === true
                          ? 'PASS'
                          : t.pass === false
                            ? 'FAIL'
                            : t.result.startsWith('INCONCLUSIVE')
                              ? 'INCONCLUSIVE'
                              : 'NOT RUN'}
                      </span>
                      <div className="small">{t.result}</div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
            <div className="faint small" style={{ marginTop: 6 }}>
              Generated {v.generated}
            </div>
          </>
        )}
      </div>
      {v?.convergence && (
        <div className="card">
          <h3>
            Why 35 km is not enough{' '}
            <span className="faint" style={{ textTransform: 'none', letterSpacing: 0 }}>
              validation test 3
            </span>
          </h3>
          <div className="small muted" style={{ marginBottom: 8 }}>
            Same sites, same 29.5-day window, only the horizon reach and azimuth resolution change.
          </div>
          <div className="grid cards">
            {v.convergence.map((c) => (
              <div key={c.site}>
                <b>{c.site}</b>
                <table>
                  <thead>
                    <tr>
                      <th>Setting</th>
                      <th>Sunlit</th>
                      <th>Max horizon</th>
                    </tr>
                  </thead>
                  <tbody>
                    {c.rows.map((r) => (
                      <tr key={r.label}>
                        <td>{r.label}</td>
                        <td>{r.sunPct.toFixed(1)}%</td>
                        <td>{r.maxHorizon.toFixed(2)}°</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            ))}
          </div>
        </div>
      )}
      {v?.external?.pgda && (
        <div className="card">
          <h3>
            Against independent data, in detail{' '}
            <span className="faint" style={{ textTransform: 'none', letterSpacing: 0 }}>
              tests 5, 6 and 10 · thresholds fixed in advance (data-pipeline/VALIDATION_PROTOCOL.md)
            </span>
          </h3>
          <div className="small muted" style={{ marginBottom: 10 }}>
            How our numbers compare with each reference. “Ours” is the mean of our value over points whose reference
            falls in the bin.
          </div>
          <div className="grid cards">
            <CalTable title="PGDA Sun, 85–90°S" rows={v.external.pgda.calibrationSun} />
            <CalTable title="PGDA Earth, 85–90°S" rows={v.external.pgda.calibrationEarth} />
            {v.external.wacPct && (
              <CalTable title="LROC WAC percent-lit, 88–90°S" rows={v.external.wacPct.calibration} />
            )}
          </div>
          <h4 style={{ margin: '14px 0 4px', fontSize: 13 }}>PGDA by terrain domain</h4>
          <table>
            <thead>
              <tr>
                <th>Domain</th>
                <th>n</th>
                <th>Sun bias</th>
                <th>Sun r</th>
                <th>Earth bias</th>
                <th>Earth r</th>
              </tr>
            </thead>
            <tbody>
              {v.external.pgda.byDomain.map((d) => (
                <tr key={d.domain}>
                  <td>{d.domain}</td>
                  <td>{d.n}</td>
                  <td>
                    {d.sunBias >= 0 ? '+' : ''}
                    {f(d.sunBias, 2)}
                  </td>
                  <td style={{ color: d.sunR < 0.95 ? 'var(--warn)' : undefined }}>{f(d.sunR, 3)}</td>
                  <td>
                    {d.earthBias >= 0 ? '+' : ''}
                    {f(d.earthBias, 2)}
                  </td>
                  <td style={{ color: d.earthR < 0.95 ? 'var(--warn)' : undefined }}>{f(d.earthR, 3)}</td>
                </tr>
              ))}
            </tbody>
          </table>
          {v.external.frames && (
            <>
              <h4 style={{ margin: '14px 0 4px', fontSize: 13 }}>
                LROC WAC frames at their UTC <span className="faint">(MCC: 1 = perfect, 0 = chance)</span>
              </h4>
              <table>
                <thead>
                  <tr>
                    <th>Frame UTC</th>
                    <th>Points</th>
                    <th>Lit in image</th>
                    <th>Lit predicted</th>
                    <th>MCC</th>
                    <th>Mirrored az</th>
                    <th>+7 days</th>
                  </tr>
                </thead>
                <tbody>
                  {v.external.frames.rows.map((r) => (
                    <tr key={r.frame}>
                      <td>{r.utc.replace('T', ' ')}</td>
                      <td>{r.points}</td>
                      <td>{f(r.litImagePct, 0)}%</td>
                      <td>{f(r.litPredictedPct, 0)}%</td>
                      <td>
                        <b>{f(r.mcc, 2)}</b>
                      </td>
                      <td>{f(r.mccMirrored, 2)}</td>
                      <td>{f(r.mccShifted7d, 2)}</td>
                    </tr>
                  ))}
                  <tr>
                    <td>
                      <b>Pooled</b>
                    </td>
                    <td></td>
                    <td></td>
                    <td></td>
                    <td>
                      <b>{f(v.external.frames.pooledMcc.real, 3)}</b>
                    </td>
                    <td>{f(v.external.frames.pooledMcc.mirrored, 3)}</td>
                    <td>{f(v.external.frames.pooledMcc.shifted7d, 3)}</td>
                  </tr>
                </tbody>
              </table>
              <div className="faint small" style={{ marginTop: 6 }}>
                Frame orientation was re-scanned over all 8 flips/rotations as a check: identity scores{' '}
                {f(v.external.frames.orientationScan.identity, 3)}, the next best{' '}
                {f(
                  Math.max(
                    ...Object.entries(v.external.frames.orientationScan)
                      .filter(([k]) => k !== 'identity')
                      .map(([, x]) => x),
                  ),
                  3,
                )}
                .
              </div>
            </>
          )}
        </div>
      )}
      <div className="card">
        <h3>What this is not</h3>
        <ul className="small" style={{ margin: 0, paddingLeft: 18, lineHeight: 1.7 }}>
          <li>Not a certified mission-design tool. It is a fast first-look planner.</li>
          <li>
            <b>Comms is geometric.</b> A link exists when a Deep Space Network station is above its elevation mask and
            above the lander’s terrain horizon. No link budget, data rate, solar-exclusion or antenna pattern is
            modelled.
          </li>
          <li>
            <b>Power is first-order:</b> rated array × visible Sun-disc fraction, vertical array tracking the Sun in
            azimuth, an editable battery balance. Hardware defaults are illustrative placeholders.
          </li>
          <li>
            <b>Terrain:</b> LOLA GDR polar DEMs (20 m to 80°S, 240 m to 60°S), no error clones propagated: the ± bands
            are neighbour-cell sensitivity (±120 m), not DEM-error P10–P90.
          </li>
          <li>
            Far field uses a 480 m area-averaged DEM beyond 40 km, which slightly under-states narrow peaks. Reach is
            300 km, DEM extended to 70°S.
          </li>
          <li>
            Points outside the nine regions use 240 m polar terrain (flagged <i>240 m</i>); sites away from the south
            pole (Apollo, Chang'e, CLPS mare targets) use the LOLA global grid LDEM_16 at about 1.9 km, which captures
            mountains on the horizon but not boulders or small craters near the lander.
          </li>
          <li>
            <b>No atmosphere, no refraction.</b> The horizon is the terrain itself or the limb of the sphere; a body is
            up when its disc clears that line (JPL Horizons reports the same airless geometry).
          </li>
          <li>
            Maps use “Earth centre above horizon”, 1° azimuth bins, and no eclipse; the cell inspector re-evaluates with
            the exact point engine.
          </li>
          <li>
            Ephemeris: SPICE DE440 baked hourly for 2026–2044 and interpolated between hours (largest error against
            SPICE in test 1: under 0.001°). Arrival dates are limited to that span.
          </li>
          <li>
            Illumination is checked against PGDA long-term averages (tests 5) and LROC WAC imagery (tests 6, 10), but
            only at 85–90°S and mostly within 38 km of the pole; the Artemis III regions outside that disc are covered
            by test 5 only for six of them, and not at all by imagery.
          </li>
        </ul>
      </div>
      {v && (
        <div className="card">
          <h3>Known gaps</h3>
          <ul className="small" style={{ margin: 0, paddingLeft: 18, lineHeight: 1.7 }}>
            {v.gaps.map((g, i) => (
              <li key={i}>{g}</li>
            ))}
          </ul>
        </div>
      )}
      <div className="card">
        <h3>Data &amp; sources</h3>
        <ul className="small" style={{ margin: 0, paddingLeft: 18, lineHeight: 1.7 }}>
          <li>
            LOLA gridded data records (PDS Geosciences Node mirror at imbrium.mit.edu): polar stereographic LDEM_80S_20M
            and LDEM_60S_240M, global simple-cylindrical LDEM_16.
          </li>
          <li>
            SPICE: NAIF DE440s, lunar PCK <code>moon_pa_de440_200625.bpc</code>, frame kernel{' '}
            <code>moon_de440_250416.tf</code>, Earth orientation <code>earth_1962_260806_2126_combined.bpc</code>.
          </li>
          <li>
            Candidate sites: Wueller et al. 2026, JGR Planets 131(3) e2025JE009434; dataset Zenodo
            10.5281/zenodo.17084058 (CC-BY-4.0). Region centres, representative-site choice and the Shackleton teaching
            site are ours.
          </li>
          <li>
            Ephemeris cross-check: NASA/JPL Horizons API (DE441), observer on the lunar surface (validation test 12).
          </li>
          <li>
            Mission landing sites: published lander positions (mostly LROC NAC measurements) for Apollo, Luna, Chang'e,
            Chandrayaan-3, SLIM and Intuitive Machines; announced targets are approximate.
          </li>
          <li>
            Method lineage: Mazarico et al. 2011 (horizon method); Barker et al. 2021 (5 m LOLA DEMs); NASA Artemis III
            candidate regions (Oct 2024).
          </li>
        </ul>
      </div>
    </div>
  );
}
